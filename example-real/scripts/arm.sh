#!/bin/bash
# usage: scripts/arm.sh plain|engine   writes src/boot.ts for the arm; set REAL_PLAIN=1 for the plain Metro config
#        SHADEWIND_TRANSITION=blur:250 scripts/arm.sh engine   also bakes a theme transition in (for Android; src/transitionConfig.ts)
cd "$(dirname "$0")/.."
if [ "$1" = "engine" ]; then
  # native cn: the table is generated from this app's sources, tailwind-merge is the oracle
  node ../bin/cn-table.mjs src -o /tmp/shadewind-cn-table.tsv > /dev/null
  node -e "const t=require('fs').readFileSync('/tmp/shadewind-cn-table.tsv','utf8'); require('fs').writeFileSync('src/cnTable.ts','// generated by scripts/arm.sh (shadewind-cn-table)\nexport const TABLE = '+JSON.stringify(t)+';\n')"
  printf "import { clsx } from 'clsx';\nimport { twMerge } from 'tailwind-merge';\nimport { cn as nativeCn, configureCn } from 'shadewind';\nimport { TABLE } from './cnTable';\n\nconfigureCn({ table: TABLE, fallback: (...a) => twMerge(clsx(a)) });\n\nexport const cn = (...inputs: Parameters<typeof nativeCn>) => nativeCn(...inputs);\n" > src/cnImpl.ts
  printf "import { installUniwind } from 'shadewind/uniwind';\n\nexport { decisions, nativeResolver, renders } from 'shadewind/uniwind';\nexport const status = () => JSON.stringify(installUniwind());\n" > src/engineReport.ts
  cat > src/boot.ts <<'BOOT'
import { Settings } from 'react-native';
import { setDefaultTransition } from 'shadewind';
import { installUniwind, nativeResolver } from 'shadewind/uniwind';
import { TRANSITION } from './transitionConfig';

// -realDebug 1 collects why each className was or was not handed to the engine (Account > Engine report)
if (Settings.get('realDebug')) {
  (globalThis as { __SHADEWIND_DEBUG__?: boolean }).__SHADEWIND_DEBUG__ = true;
}

// -engineOff 1: the adapter's components without the engine (no registration), for A/B launches of one build
if (Settings.get('engineOff')) {
  (globalThis as { __SHADEWIND_ENGINE_OFF__?: boolean }).__SHADEWIND_ENGINE_OFF__ = true;
}

// -markers 1 / -weakSub 1: option-2 experiment flags (read by the engine at install / first use)
if (Settings.get('markers')) {
  (globalThis as { __SHADEWIND_MARKERS__?: boolean }).__SHADEWIND_MARKERS__ = true;
}

if (Settings.get('weakSub')) {
  (globalThis as { __SHADEWIND_WEAK_SUBSCRIBE__?: boolean }).__SHADEWIND_WEAK_SUBSCRIBE__ = true;
}

// -resolverOff 1: Uniwind's own class resolution only (no class table loaded or built), for A/B launches of one build
if (Settings.get('resolverOff')) {
  nativeResolver.setEnabled(false);
}

// the theme transition for Uniwind.setTheme, if one is asked for (src/transitionConfig.ts): the adapter's default
if (TRANSITION) {
  setDefaultTransition(TRANSITION);
}

installUniwind();
BOOT
  # the theme transition baked into the bundle for Android, which has no launch arguments: SHADEWIND_TRANSITION=blur:250 (or fade:250)
  transition="${SHADEWIND_TRANSITION:-}"
  if [ -n "$transition" ] && ! printf '%s' "$transition" | grep -Eq '^(fade|blur):[0-9]+$'; then
    echo "SHADEWIND_TRANSITION must look like fade:250 or blur:250; ignored: $transition" >&2
    transition=""
  fi
  printf "// generated by scripts/arm.sh: SHADEWIND_TRANSITION at arm time ('' = none; launch arguments still apply on iOS)\nexport const ARM_TRANSITION: string | null = '%s';\n" "$transition" > src/transitionArm.ts
else
  printf "import { clsx, type ClassValue } from 'clsx';\nimport { twMerge } from 'tailwind-merge';\n\nexport const cn = (...inputs: ClassValue[]) => twMerge(clsx(inputs));\n" > src/cnImpl.ts
  printf "export const decisions = new Map<string, string>();\nexport const renders = new Map<string, number>();\nexport const nativeResolver = null as null | typeof import('shadewind/uniwind').nativeResolver;\nexport const status = () => 'plain arm: no engine';\n" > src/engineReport.ts
  printf "export {};\n" > src/boot.ts
  printf "// generated by scripts/arm.sh: the plain arm has no engine, so no theme transition\nexport const ARM_TRANSITION: string | null = null;\n" > src/transitionArm.ts
fi
echo "arm: $1"
